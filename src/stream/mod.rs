//! Real-time streaming of agent step events.
//!
//! `DefaultAgent` emits a `StreamEvent` at each meaningful boundary —
//! assistant message, bash start/result, observation, format error, run
//! start/end. A `StreamSink` decouples emission from transport: tests use
//! an in-memory sink, production wires a `BroadcastSink` whose events are
//! served over HTTP/SSE by `sse::SseServer`.
//!
//! Disconnect-safety is the load-bearing requirement (spec AC #3): emit
//! must never block or fail. `BroadcastSink::emit` ignores `SendError`
//! when there are zero subscribers, and the SSE per-connection task drops
//! on the first write error without disturbing other clients or the agent.

use serde::Serialize;

pub mod broadcast;
pub mod sse;
#[cfg(feature = "webhook")]
pub mod webhook;

pub use broadcast::BroadcastSink;
pub use sse::SseServer;
#[cfg(feature = "webhook")]
pub use webhook::{WebhookSink, WebhookSinkError};

/// One step-level event in the agent trajectory.
///
/// Serialized as JSON with a `type` discriminator; SSE frames use the
/// same string as the `event:` field name so clients can `addEventListener`
/// per kind.
#[derive(Debug, Clone, Serialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum StreamEvent {
    /// Emitted once at agent start, after the system + instance prompts
    /// are recorded.
    RunStarted {
        /// The task description given to the agent.
        task: String,
        /// The name of the LLM model being used.
        model: String,
        /// The ISO 8601 timestamp of when the run started.
        started_at: String,
    },
    /// LLM produced a response (before action parsing).
    AssistantMessage {
        /// The current step number in the trajectory.
        step: u32,
        /// The raw content generated by the assistant.
        content: String,
        /// The total cost of the interaction in USD, if available.
        cost_usd: Option<f64>,
        /// The ISO 8601 timestamp of when the message was generated.
        timestamp: String,
    },
    /// About to execute a bash command.
    BashStart {
        /// The current step number in the trajectory.
        step: u32,
        /// The shell command being executed.
        command: String,
        /// The ISO 8601 timestamp of when the execution started.
        timestamp: String,
    },
    /// Bash command finished.
    BashResult {
        /// The current step number in the trajectory.
        step: u32,
        /// The exit code of the executed command.
        exit_code: i32,
        /// The standard output emitted by the command.
        stdout: String,
        /// The standard error emitted by the command.
        stderr: String,
        /// Whether the command was terminated due to a timeout.
        timed_out: bool,
        /// The ISO 8601 timestamp of when the execution finished.
        timestamp: String,
    },
    /// Observation message recorded into the trajectory after a bash run.
    Observation {
        /// The current step number in the trajectory.
        step: u32,
        /// The observation content (typically truncated outputs).
        content: String,
        /// The ISO 8601 timestamp of the observation.
        timestamp: String,
    },
    /// Model output was malformed; format-error template was sent back.
    FormatError {
        /// The current step number in the trajectory.
        step: u32,
        /// The error details sent back to the model to correct its format.
        content: String,
        /// The ISO 8601 timestamp of the error.
        timestamp: String,
    },
    /// Agent loop ended.
    RunEnded {
        /// The reason the run terminated (e.g. success, error).
        exit_reason: String,
        /// The specific failure category if the run failed.
        #[serde(skip_serializing_if = "Option::is_none")]
        failure_category: Option<crate::trajectory::FailureCategory>,
        /// The final answer produced by the agent, if any.
        final_output: Option<String>,
        /// Total steps executed during the run.
        steps: u32,
        /// Total accumulated LLM cost for the entire run.
        total_cost_usd: f64,
        /// The ISO 8601 timestamp of when the run ended.
        ended_at: String,
    },
}

impl StreamEvent {
    /// Stable wire name; used as the SSE `event:` field.
    pub fn event_name(&self) -> &'static str {
        match self {
            Self::RunStarted { .. } => "run_started",
            Self::AssistantMessage { .. } => "assistant_message",
            Self::BashStart { .. } => "bash_start",
            Self::BashResult { .. } => "bash_result",
            Self::Observation { .. } => "observation",
            Self::FormatError { .. } => "format_error",
            Self::RunEnded { .. } => "run_ended",
        }
    }
}

/// Sink the agent emits to. Implementations MUST be non-blocking and
/// MUST NOT fail visibly to the agent — disconnect handling is the
/// sink's job.
pub trait StreamSink: Send + Sync {
    /// Emits a single `StreamEvent` into the sink.
    ///
    /// This method must be non-blocking and should handle internal buffering or dispatching.
    fn emit(&self, event: StreamEvent);
}

/// No-op sink. Useful as a default when streaming is disabled, so the
/// agent loop doesn't branch on `Option<...>` at every emission point.
#[derive(Debug, Default, Clone, Copy)]
pub struct NullSink;

impl StreamSink for NullSink {
    fn emit(&self, _event: StreamEvent) {}
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]
    use super::*;

    #[test]
    fn event_names_are_snake_case() {
        let e = StreamEvent::RunStarted {
            task: "t".into(),
            model: "m".into(),
            started_at: "now".into(),
        };
        assert_eq!(e.event_name(), "run_started");
    }

    #[test]
    fn serializes_with_type_tag() {
        let e = StreamEvent::BashStart {
            step: 3,
            command: "echo hi".into(),
            timestamp: "t".into(),
        };
        let json = serde_json::to_value(&e).unwrap();
        assert_eq!(json["type"], "bash_start");
        assert_eq!(json["step"], 3);
        assert_eq!(json["command"], "echo hi");
    }

    #[test]
    fn null_sink_swallows_events() {
        let s = NullSink;
        s.emit(StreamEvent::RunStarted {
            task: "t".into(),
            model: "m".into(),
            started_at: "s".into(),
        });
    }
}
